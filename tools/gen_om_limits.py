#!/usr/bin/env python3
"""Generate docs/reference/om-limits.md from engines/*.json.

Run from the repository root:  python3 docs/tools/gen_om_limits.py
The page is committed; re-run whenever an engine profile changes.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ENGINES = ["916iS", "915iS", "912iS"]
OUT = ROOT / "docs" / "reference" / "om-limits.md"


def fmt(v, unit):
    if v is None:
        return "—"
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    s = f"{v:,}" if isinstance(v, int) else f"{v:g}"
    return f"{s} {unit}".replace(" °", "°")


def load(engine):
    with open(ROOT / "engines" / f"{engine}.json") as f:
        return json.load(f)


def limit_cell(lim):
    if lim is None:
        return "—"
    unit = lim.get("unit", "")
    lo, hi = lim.get("min_val"), lim.get("max_val")
    if lo is not None and hi is not None:
        return f"{fmt(lo, unit)} – {fmt(hi, unit)}"
    if lo is not None:
        return f"≥ {fmt(lo, unit)}"
    return f"≤ {fmt(hi, unit)}"


def suppression(lim):
    parts = []
    if lim.get("phases"):
        parts.append("checked only during " + ", ".join(p.lower() for p in lim["phases"]))
    if lim.get("min_duration_s"):
        parts.append(f"must persist {lim['min_duration_s']} s")
    mdp = lim.get("min_duration_by_phase")
    if mdp:
        on = [f"{k.lower()} {v} s" for k, v in mdp.items() if v]
        off = [k.lower() for k, v in mdp.items() if not v]
        if on:
            parts.append("must persist " + ", ".join(on))
        if off:
            parts.append("not checked during " + ", ".join(off))
    if lim.get("suppress_phases"):
        parts.append("not checked during " + ", ".join(p.lower() for p in lim["suppress_phases"]))
    if lim.get("min_rpm"):
        parts.append(f"engine at or above {lim['min_rpm']:,} rpm")
    if lim.get("requires_reached_since_start"):
        parts.append("after first reached this flight")
    if lim.get("report_in_exceedances") is False:
        parts.append("noted on the card, not an event")
    fp = lim.get("filter_policy") or {}
    if fp.get("filterable") is False:
        parts.append("never filterable")
    return "; ".join(parts) if parts else "—"


def main():
    profiles = {e: load(e) for e in ENGINES}
    # Union of limit ids in first-seen order
    order, labels = [], {}
    for e in ENGINES:
        for lim in profiles[e]["limits"]:
            if lim["id"] not in labels:
                order.append(lim["id"])
                labels[lim["id"]] = lim["label"]
    by_engine = {e: {l["id"]: l for l in profiles[e]["limits"]} for e in ENGINES}

    lines = []
    lines.append("# Operators Manual limits by engine\n")
    lines.append("<!-- Generated by docs/tools/gen_om_limits.py from engines/*.json — do not edit by hand. -->\n")
    lines.append(
        "These are the limits the app checks every flight against, taken from each engine's Rotax "
        "Operators Manual. The same table, for your workspace's engine, is under **Settings → Engine** in the app. "
        "How a limit becomes an event — minimum durations, phase suppression, the 30 s merge gap — is explained in "
        "[Operators Manual limits and events](../concepts/limits-and-events.md).\n"
    )
    lines.append("## Sources\n")
    lines.append("| Engine | Operators Manual | Rated power | Turbocharged |")
    lines.append("|---|---|---|---|")
    for e in ENGINES:
        p = profiles[e]
        m = p.get("_metadata", {})
        om = m.get("om_reference") or m.get("source") or m.get("om") or ""
        if isinstance(om, dict):
            om = ", ".join(str(v) for v in om.values())
        lines.append(
            f"| {e} | {om} | {p.get('rated_power_hp','?')} hp / {p.get('rated_power_kw','?')} kW at {p.get('rated_rpm','?'):,} rpm | "
            f"{'yes' if p.get('turbocharged') else 'no'} |"
        )
    lines.append("")
    lines.append("## Limits\n")
    lines.append("| Limit | " + " | ".join(ENGINES) + " | Label |")
    lines.append("|---|" + "---|" * len(ENGINES) + "---|")
    for lid in order:
        cells = [limit_cell(by_engine[e].get(lid)) for e in ENGINES]
        sev = next((by_engine[e][lid].get("severity", "") for e in ENGINES if lid in by_engine[e]), "")
        lines.append(f"| {labels[lid]} | " + " | ".join(cells) + f" | {sev} |")
    # EGT split and takeoff power
    lines.append("")
    lines.append("## EGT split and takeoff power\n")
    lines.append("| Rule | " + " | ".join(ENGINES) + " |")
    lines.append("|---|" + "---|" * len(ENGINES))
    row_hi, row_lo = [], []
    for e in ENGINES:
        s = profiles[e].get("egt_spread")
        if s:
            row_hi.append(f"≤ {fmt(s['high_flow_spread_limit_f'], '°F')} above {s['high_flow_threshold_lph']:g} L/h fuel flow")
            row_lo.append(f"≤ {fmt(s['low_flow_spread_limit_f'], '°F')} below {s['high_flow_threshold_lph']:g} L/h")
        else:
            row_hi.append("no EGT split limit")
            row_lo.append("—")
    lines.append("| EGT split (normal fuel flow) | " + " | ".join(row_hi) + " |")
    lines.append("| EGT split (low fuel flow) | " + " | ".join(row_lo) + " |")
    ob = []
    for e in ENGINES:
        o = profiles[e]["overboost"]
        ob.append(f"≤ {o['limit_s']} s above {o['rpm_threshold']:,} rpm or {o['power_pct_threshold']} % power; close call within {o['close_call_margin_s']} s")
    lines.append("| Time at takeoff power | " + " | ".join(ob) + " |")
    lines.append("")
    lines.append("## When each limit is checked\n")
    lines.append("Phase suppression and minimum durations for the 916iS profile. Other engines use the same rules unless noted in the app.\n")
    lines.append("| Limit | Checked |")
    lines.append("|---|---|")
    for lid in order:
        lim = by_engine["916iS"].get(lid) or next(by_engine[e][lid] for e in ENGINES if lid in by_engine[e])
        lines.append(f"| {labels[lid]} | {suppression(lim)} |")
    lines.append("")
    lines.append("*Bus voltage limits are not Operators Manual limits; they are a check for 12 V installations that the app includes because a charging fault shows there first.*\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
