// Persistence probe — worker (Spec 04 v0.6 §9.4, step 3).
//
// Runs every check that needs a worker: OPFS with synchronous access
// handles only exists here. Generated data only; no log file is ever read.
// Each request is {id, op, args}; each reply is {id, ok, result|error}.

const PYODIDE_VERSION = "0.28.0";
const PYODIDE_CDN = `https://cdn.jsdelivr.net/pyodide/v${PYODIDE_VERSION}/full/`;
const ROOT_DIR = "eis-persistence-probe";        // the probe's own OPFS folder
const MOUNT = "/data";                             // where Python sees it
const IDB_MOUNT = "/idbdata";
const MB = 1024 * 1024;

let pyodide = null;
let nativefs = null;

const now = () => performance.now();
const ms = (t0) => Math.round((performance.now() - t0) * 10) / 10;

async function sha256(buf) {
  const d = await crypto.subtle.digest("SHA-256", buf);
  return [...new Uint8Array(d)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

async function rootDir() {
  const top = await navigator.storage.getDirectory();
  return top.getDirectoryHandle(ROOT_DIR, { create: true });
}

async function estimate() {
  try {
    const e = await navigator.storage.estimate();
    return { usage: e.usage ?? null, quota: e.quota ?? null };
  } catch (e) {
    return { error: String(e) };
  }
}

// 1. OPFS available in a worker, with synchronous access handles.
async function checkOpfs() {
  const t0 = now();
  const dir = await rootDir();
  const fh = await dir.getFileHandle("sync-test.bin", { create: true });
  const h = await fh.createSyncAccessHandle();
  const data = new TextEncoder().encode("persistence probe — sync access handle");
  h.truncate(0);
  h.write(data, { at: 0 });
  h.flush();
  const back = new Uint8Array(h.getSize());
  h.read(back, { at: 0 });
  h.close();
  await dir.removeEntry("sync-test.bin");
  const ok = new TextDecoder().decode(back) === new TextDecoder().decode(data);
  return { pass: ok, ms: ms(t0), detail: ok ? "created, written, read back" : "read-back mismatch" };
}

// 2. 50 MB write / read round trip with a checksum.
function fill(buf, seed) {
  // xorshift32: generated bytes, the same for a given seed.
  let x = seed >>> 0 || 1;
  const u32 = new Uint32Array(buf.buffer, buf.byteOffset, buf.byteLength >>> 2);
  for (let i = 0; i < u32.length; i++) {
    x ^= x << 13; x >>>= 0; x ^= x >>> 17; x ^= x << 5; x >>>= 0;
    u32[i] = x;
  }
}

async function checkRoundTrip(sizeMb) {
  const size = sizeMb * MB;
  const before = await estimate();
  const dir = await rootDir();
  const data = new Uint8Array(size);
  fill(data, 0x5eed);
  const want = await sha256(data);

  const fh = await dir.getFileHandle("roundtrip.bin", { create: true });
  let h = await fh.createSyncAccessHandle();
  h.truncate(0);
  const tw = now();
  const CHUNK = 4 * MB;
  for (let off = 0; off < size; off += CHUNK) h.write(data.subarray(off, off + CHUNK), { at: off });
  h.flush();
  const writeMs = ms(tw);
  h.close();
  const after = await estimate();

  h = await fh.createSyncAccessHandle();
  const back = new Uint8Array(h.getSize());
  const tr = now();
  h.read(back, { at: 0 });
  const readMs = ms(tr);
  h.close();
  const got = await sha256(back);
  await dir.removeEntry("roundtrip.bin");
  const afterRemove = await estimate();
  return {
    pass: got === want && back.length === size, size_mb: sizeMb, write_ms: writeMs, read_ms: readMs,
    write_mb_s: Math.round((sizeMb / (writeMs / 1000)) * 10) / 10,
    read_mb_s: Math.round((sizeMb / (readMs / 1000)) * 10) / 10,
    checksum_match: got === want, estimate_before: before, estimate_after_write: after,
    estimate_after_remove: afterRemove,
  };
}

// 3. Pyodide with the OPFS folder mounted; Python writes Spec 02 §5.8's layout.
async function loadPyodideOnce() {
  if (pyodide) return { load_ms: 0, already: true };
  const t0 = now();
  importScripts(PYODIDE_CDN + "pyodide.js");
  pyodide = await self.loadPyodide({ indexURL: PYODIDE_CDN });
  return { load_ms: ms(t0), version: pyodide.version };
}

async function mountOpfs() {
  if (nativefs) return { mount_ms: 0, already: true };
  const t0 = now();
  const dir = await rootDir();
  nativefs = await pyodide.mountNativeFS(MOUNT, dir);
  return { mount_ms: ms(t0) };
}

const PY_WRITE = `
import json, os
root = ${JSON.stringify(MOUNT)}
nonce = NONCE
registry = {"version": "1", "workspaces": [{"id": "ws_probe", "name": "Persistence probe",
            "engine_model": "916iS", "created_at": nonce}]}
manifest = {"id": "ws_probe", "name": "Persistence probe", "engine_model": "916iS",
            "log_folders": [], "schema_version": "02-v0.5", "created_at": nonce,
            "storage_backend": "opfs", "flight_count": 0}
os.makedirs(f"{root}/workspaces/ws_probe/flights", exist_ok=True)
texts = {"registry.json": json.dumps(registry, indent=2),
         "workspaces/ws_probe/manifest.json": json.dumps(manifest, indent=2)}
for rel, text in texts.items():
    with open(f"{root}/{rel}", "w") as f:
        f.write(text)
json.dumps(texts)
`;

const PY_READ = `
import json, os
root = ${JSON.stringify(MOUNT)}
out = {}
for rel in ("registry.json", "workspaces/ws_probe/manifest.json"):
    p = f"{root}/{rel}"
    out[rel] = open(p).read() if os.path.isfile(p) else None
json.dumps({"texts": out, "flights_dir": os.path.isdir(f"{root}/workspaces/ws_probe/flights")})
`;

async function jsReadOpfs(rel) {
  // A plain OPFS read on the JS side, not through Pyodide.
  try {
    let dir = await rootDir();
    const parts = rel.split("/");
    for (const p of parts.slice(0, -1)) dir = await dir.getDirectoryHandle(p);
    const f = await (await dir.getFileHandle(parts[parts.length - 1])).getFile();
    return await f.text();
  } catch (e) {
    return null;
  }
}

async function checkPyodideWrite() {
  const load = await loadPyodideOnce();
  const mount = await mountOpfs();
  const nonce = new Date().toISOString();
  const t0 = now();
  const texts = JSON.parse(pyodide.runPython(PY_WRITE.replace("NONCE", JSON.stringify(nonce))));
  const writeMs = ms(t0);
  // Before flushing: is a Python write already visible to JS?
  const visibleBefore = (await jsReadOpfs("registry.json")) === texts["registry.json"];
  const tf = now();
  await nativefs.syncfs();
  const flushMs = ms(tf);
  const visible = {};
  for (const rel of Object.keys(texts)) visible[rel] = (await jsReadOpfs(rel)) === texts[rel];
  const readBack = JSON.parse(pyodide.runPython(PY_READ));
  const pythonReadOk = Object.keys(texts).every((rel) => readBack.texts[rel] === texts[rel]);
  const hashes = {};
  for (const [rel, t] of Object.entries(texts)) hashes[rel] = await sha256(new TextEncoder().encode(t));
  const visibleAfterFlush = Object.values(visible).every(Boolean);
  return {
    pass: pythonReadOk && visibleAfterFlush, pyodide_version: pyodide.version, load_ms: load.load_ms,
    mount_ms: mount.mount_ms, python_write_ms: writeMs, flush_ms: flushMs,
    visible_to_js_before_flush: visibleBefore, visible_to_js_after_flush: visibleAfterFlush,
    python_read_back: pythonReadOk, nested_dirs: readBack.flights_dir, hashes,
  };
}

// 4 / 5. After a reload or a restart: the same documents, from Python and JS.
async function checkDocuments(expected) {
  const load = await loadPyodideOnce();
  const mount = await mountOpfs();
  await nativefs.syncfs();          // pull what is on OPFS into the mount
  const readBack = JSON.parse(pyodide.runPython(PY_READ));
  const result = { load_ms: load.load_ms, mount_ms: mount.mount_ms, documents: {} };
  let all = true;
  for (const [rel, want] of Object.entries(expected || {})) {
    const py = readBack.texts[rel];
    const js = await jsReadOpfs(rel);
    const pyHash = py == null ? null : await sha256(new TextEncoder().encode(py));
    const jsHash = js == null ? null : await sha256(new TextEncoder().encode(js));
    const same = pyHash === want && jsHash === want;
    result.documents[rel] = { present_python: py != null, present_js: js != null, identical: same };
    all = all && same;
  }
  result.pass = all && Object.keys(expected || {}).length > 0;
  result.registry_present = readBack.texts["registry.json"] != null;
  return result;
}

async function registryPresent() {
  return (await jsReadOpfs("registry.json")) != null;
}

// 8. Fallback: the same document round trip through Emscripten's IDBFS.
const PY_IDB_WRITE = PY_WRITE.replace(JSON.stringify(MOUNT), JSON.stringify(IDB_MOUNT));
const PY_IDB_READ = PY_READ.replace(JSON.stringify(MOUNT), JSON.stringify(IDB_MOUNT));

function idbSync(populate) {
  return new Promise((resolve, reject) => pyodide.FS.syncfs(populate, (err) => (err ? reject(err) : resolve())));
}

async function idbMount() {
  const FS = pyodide.FS;
  if (!FS.analyzePath(IDB_MOUNT).exists) FS.mkdir(IDB_MOUNT);
  try {
    FS.mount(FS.filesystems.IDBFS, {}, IDB_MOUNT);
  } catch (e) {
    if (!String(e).includes("busy")) throw e;   // already mounted
  }
  await idbSync(true);
}

async function checkIdbfsWrite() {
  await loadPyodideOnce();
  const t0 = now();
  await idbMount();
  const mountMs = ms(t0);
  const nonce = new Date().toISOString();
  const texts = JSON.parse(pyodide.runPython(PY_IDB_WRITE.replace("NONCE", JSON.stringify(nonce))));
  const tf = now();
  await idbSync(false);
  const flushMs = ms(tf);
  const readBack = JSON.parse(pyodide.runPython(PY_IDB_READ));
  const hashes = {};
  for (const [rel, t] of Object.entries(texts)) hashes[rel] = await sha256(new TextEncoder().encode(t));
  return { pass: Object.keys(texts).every((r) => readBack.texts[r] === texts[r]), mount_ms: mountMs,
           flush_ms: flushMs, hashes };
}

async function checkIdbfsDocuments(expected) {
  await loadPyodideOnce();
  await idbMount();
  const readBack = JSON.parse(pyodide.runPython(PY_IDB_READ));
  const documents = {};
  let all = true;
  for (const [rel, want] of Object.entries(expected || {})) {
    const t = readBack.texts[rel];
    const same = t != null && (await sha256(new TextEncoder().encode(t))) === want;
    documents[rel] = { present: t != null, identical: same };
    all = all && same;
  }
  return { pass: all && Object.keys(expected || {}).length > 0, documents };
}

// Start over: the probe's OPFS folder and its IndexedDB store.
async function reset() {
  const top = await navigator.storage.getDirectory();
  try { await top.removeEntry(ROOT_DIR, { recursive: true }); } catch (e) { /* none yet */ }
  await new Promise((resolve) => {
    const req = indexedDB.deleteDatabase(IDB_MOUNT);
    req.onsuccess = req.onerror = req.onblocked = () => resolve();
  });
  return { reset: true };
}

const OPS = {
  estimate, checkOpfs, checkRoundTrip, checkPyodideWrite, checkDocuments, registryPresent,
  checkIdbfsWrite, checkIdbfsDocuments, reset,
};

self.onmessage = async (ev) => {
  const { id, op, args } = ev.data;
  try {
    if (!OPS[op]) throw new Error(`unknown op ${op}`);
    const result = await OPS[op](...(args || []));
    self.postMessage({ id, ok: true, result });
  } catch (e) {
    self.postMessage({ id, ok: false, error: `${e && e.name ? e.name + ": " : ""}${e && e.message ? e.message : e}` });
  }
};
