#!/usr/bin/env python3
"""Generate the Investigations reference pages (Spec 13, Spec 16 §4.2, §4.6):

    docs/reference/investigation-tools.md    from `slingology-eis mcp tools --json`
    docs/reference/investigation-prompts.md  from the MCP server's prompts/list and prompts/get

Run from the repository root:  .venv/bin/python docs/tools/gen_investigation_reference.py
The pages are committed; re-run whenever a tool or prompt changes
(tests/unit/test_docs_reference.py fails while they are stale).
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOOLS_PAGE = ROOT / "docs" / "reference" / "investigation-tools.md"
PROMPTS_PAGE = ROOT / "docs" / "reference" / "investigation-prompts.md"

GENERATED = "<!-- Generated by docs/tools/gen_investigation_reference.py — do not edit by hand. -->"


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def _type(schema: dict) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        return " or ".join(_type(s) for s in schema["anyOf"])
    t = schema.get("type", "")
    if t == "array":
        return f"list of {_type(schema.get('items', {})) or 'values'}"
    bounds = [f"{k} {schema[k]}" for k in ("minimum", "maximum") if k in schema]
    return t + (f" ({', '.join(bounds)})" if bounds else "")


def tools_page(tools: list[dict]) -> str:
    out = [GENERATED, "", "# Investigation tools", "",
           "The tools the EIS extension gives Claude (Spec 16 §4.2). Claude calls them; you don't need to — this page "
           "is for reading what Claude can and cannot do, and for checking a tool from the command line with "
           "`slingology-eis mcp call TOOL '{…}'`, which prints the same JSON Claude receives.", "",
           "Every result is `{engine_version, workspace_id, result}`. Tools marked **writes** change something in the "
           "workspace (a notebook, the inbox, the workspace used for the conversation); the others only read. None "
           "reaches the internet. A refusal is an error whose text says why and what to ask instead.", "",
           f"{len(tools)} tools, in the order Claude sees them.", "",
           "| Tool | | What it does |", "|---|---|---|"]
    for t in tools:
        writes = "writes" if not t.get("annotations", {}).get("readOnlyHint", True) else ""
        out.append(f"| [`{t['name']}`](#{t['name']}) | {writes} | {_cell(t['description'].split('. ')[0])} |")
    for t in tools:
        out += ["", f"## `{t['name']}`", ""]
        if not t.get("annotations", {}).get("readOnlyHint", True):
            out += ["*Writes.*", ""]
        out += [t["description"].strip(), ""]
        props = t.get("inputSchema", {}).get("properties", {})
        required = set(t.get("inputSchema", {}).get("required", []))
        if not props:
            out += ["No parameters."]
            continue
        out += ["| Parameter | Type | |", "|---|---|---|"]
        for name, schema in props.items():
            note = "required" if name in required else ""
            if schema.get("description"):
                note = (note + " — " if note else "") + _cell(schema["description"])
            out.append(f"| `{name}` | {_type(schema)} | {note} |")
    return "\n".join(out) + "\n"


def prompts_page(prompts: list[dict]) -> str:
    out = [GENERATED, "", "# Investigation prompts", "",
           "The prompts the EIS extension offers in Claude Desktop (Spec 16 §4.6): pick one from the **+** menu in a "
           "chat, fill in what it asks, and Claude starts with the EIS method in front of it. Each is shown below as "
           "Claude receives it, with the placeholders in braces.", ""]
    for p in prompts:
        out += [f"## {p['title']}", "", p["description"], ""]
        args = p.get("arguments") or []
        if args:
            out += ["| Asks for | |", "|---|---|"]
            out += [f"| `{a['name']}` | {'required — ' if a.get('required') else ''}{_cell(a.get('description', ''))} |"
                    for a in args]
            out.append("")
        body = p["text"].strip()
        out += ['??? note "The prompt"', ""] + [("    " + ln) if ln else "" for ln in body.splitlines()] + [""]
    return "\n".join(out).rstrip() + "\n"


def build() -> tuple[str, str]:
    raw = subprocess.run([sys.executable, "-m", "slingology_eis.cli", "mcp", "tools", "--json"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout
    sys.path.insert(0, str(ROOT))
    from slingology_eis.investigations.ops import list_prompts
    return tools_page(json.loads(raw)), prompts_page(list_prompts())


def main() -> int:
    tools, prompts = build()
    TOOLS_PAGE.write_text(tools)
    PROMPTS_PAGE.write_text(prompts)
    print(TOOLS_PAGE.relative_to(ROOT), PROMPTS_PAGE.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
